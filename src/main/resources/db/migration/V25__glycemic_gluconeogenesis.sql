-- Adds the GLUCONEOGENESIS category (slow rise from protein/fat) to the glycemic_events checks.

ALTER TABLE glycemic_events DROP CONSTRAINT IF EXISTS chk_glycemic_category;
ALTER TABLE glycemic_events DROP CONSTRAINT IF EXISTS chk_glycemic_detector_category;
ALTER TABLE glycemic_events DROP CONSTRAINT IF EXISTS chk_glycemic_user_label;

ALTER TABLE glycemic_events ADD CONSTRAINT chk_glycemic_category CHECK (category IN
        ('UNLOGGED_FOOD','UNDER_ESTIMATED_FOOD','STRESS','ABSORPTION_DELAY','LIPODYSTROPHY','DAWN_PHENOMENON',
         'ANAEROBIC_ACTIVITY','GLUCONEOGENESIS','UNLOGGED_INSULIN','UNDER_ESTIMATED_INSULIN','OVER_ESTIMATED_FOOD',
         'AEROBIC_ACTIVITY'));
ALTER TABLE glycemic_events ADD CONSTRAINT chk_glycemic_detector_category CHECK (detector_category IN
        ('UNLOGGED_FOOD','UNDER_ESTIMATED_FOOD','STRESS','ABSORPTION_DELAY','LIPODYSTROPHY','DAWN_PHENOMENON',
         'ANAEROBIC_ACTIVITY','GLUCONEOGENESIS','UNLOGGED_INSULIN','UNDER_ESTIMATED_INSULIN','OVER_ESTIMATED_FOOD',
         'AEROBIC_ACTIVITY'));
ALTER TABLE glycemic_events ADD CONSTRAINT chk_glycemic_user_label CHECK (user_label IS NULL OR user_label IN
        ('UNLOGGED_FOOD','UNDER_ESTIMATED_FOOD','STRESS','ABSORPTION_DELAY','LIPODYSTROPHY','DAWN_PHENOMENON',
         'ANAEROBIC_ACTIVITY','GLUCONEOGENESIS','UNLOGGED_INSULIN','UNDER_ESTIMATED_INSULIN','OVER_ESTIMATED_FOOD',
         'AEROBIC_ACTIVITY'));
